-- ESTUDIANTE----------------------------------------------------


-- INSERT
CREATE PROCEDURE SP_INS_ESTUDIANTE_CPO
    @NOMBRE VARCHAR(30),
    @AP VARCHAR(30),
    @AM VARCHAR(30),
    @EDAD INT,
    @DIRECCION VARCHAR(50),
    @TELEFONO VARCHAR(10),
    @IDCARRERA INT,
    @IDGRUPO INT
AS
BEGIN
    INSERT INTO ESTUDIANTE
    (NOMBRE, AP, AM, EDAD, DIRECCION, TELEFONO, IDCARRERA, IDGRUPO)
    VALUES
    (@NOMBRE, @AP, @AM, @EDAD, @DIRECCION, @TELEFONO, @IDCARRERA, @IDGRUPO);
END;
GO

-- UPDATE
CREATE PROCEDURE SP_UP_ESTUDIANTE_CPO
    @IDESTUDIANTE INT,
    @NOMBRE VARCHAR(30),
    @AP VARCHAR(30),
    @AM VARCHAR(30),
    @EDAD INT,
    @DIRECCION VARCHAR(50),
    @TELEFONO VARCHAR(10),
    @IDCARRERA INT,
    @IDGRUPO INT
AS
BEGIN
    UPDATE ESTUDIANTE
    SET NOMBRE = @NOMBRE,
        AP = @AP,
        AM = @AM,
        EDAD = @EDAD,
        DIRECCION = @DIRECCION,
        TELEFONO = @TELEFONO,
        IDCARRERA = @IDCARRERA,
        IDGRUPO = @IDGRUPO
    WHERE IDESTUDIANTE = @IDESTUDIANTE;
END;
GO

-- DELETE
CREATE PROCEDURE SP_DEL_ESTUDIANTE_CPO
    @IDESTUDIANTE INT
AS
BEGIN
    DELETE FROM ESTUDIANTE
    WHERE IDESTUDIANTE = @IDESTUDIANTE;
END;
GO



-- CARRERA----------------------------------------------------


-- INSERT
CREATE PROCEDURE SP_INS_CARRERA_CPO
    @NOMBRE VARCHAR(40),
    @NOMENCLATURA VARCHAR(4)
AS
BEGIN
    INSERT INTO CARRERA (NOMBRE, NOMENCLATURA)
    VALUES (@NOMBRE, @NOMENCLATURA);
END;
GO

-- UPDATE
CREATE PROCEDURE SP_UP_CARRERA_CPO
    @IDCARRERA INT,
    @NOMBRE VARCHAR(40),
    @NOMENCLATURA VARCHAR(4)
AS
BEGIN
    UPDATE CARRERA
    SET NOMBRE = @NOMBRE,
        NOMENCLATURA = @NOMENCLATURA
    WHERE IDCARRERA = @IDCARRERA;
END;
GO

-- DELETE
CREATE PROCEDURE SP_DEL_CARRERA_CPO
    @IDCARRERA INT
AS
BEGIN
    DELETE FROM CARRERA
    WHERE IDCARRERA = @IDCARRERA;
END;
GO



