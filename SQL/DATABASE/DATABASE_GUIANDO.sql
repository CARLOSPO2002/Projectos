CREATE PROCEDURE RANKING_NOMBRES
AS
BEGIN
    SELECT 
        ROW_NUMBER() OVER (ORDER BY MAX(R.PUNTAJE) DESC) AS POSICION,
        U.ID_USUARIO,
        U.NOMBRE,
        MAX(R.PUNTAJE) AS MEJOR_PUNTAJE
    FROM RECORDS R
    INNER JOIN USUARIOS U
        ON R.ID_USUARIO = U.ID_USUARIO
    GROUP BY U.ID_USUARIO, U.NOMBRE
    ORDER BY MEJOR_PUNTAJE DESC;
END;
